#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { createInterface } from "node:readline/promises";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const configPath = path.join(root, ".infra9core", "config.json");
const yes = process.argv.includes("--yes");
const force = process.argv.includes("--force-managed-files");
const gatewayExposureModes = ["private-bff", "public-supabase"];

function setEnv(source, key, value) {
  const expression = new RegExp(`^${key}=.*$`, "m");
  return expression.test(source) ? source.replace(expression, `${key}=${value}`) : `${source.trimEnd()}\n${key}=${value}\n`;
}

function renderCaddy(source, config) {
  const publicSupabase = config.deployment.gatewayExposureMode === "public-supabase";
  const gatewayRoute = publicSupabase ? [
    "\t@supabase path /auth/v1/* /rest/v1/* /realtime/v1/* /storage/v1/* /functions/v1/*",
    "\thandle @supabase {",
    `\t\treverse_proxy 127.0.0.1:${config.deployment.supabaseApiPort}`,
    "\t}",
  ].join("\n") : "";
  const studioSite = publicSupabase ? [
    `${config.deployment.studioDomain} {`,
    "\tbasic_auth {",
    "\t\t{$STUDIO_HTTP_USER} {$STUDIO_HTTP_PASSWORD_HASH}",
    "\t}",
    `\treverse_proxy 127.0.0.1:${config.deployment.supabaseStudioPort}`,
    "}",
  ].join("\n") : "";
  return `# Managed by Infra9CORE. Re-run make infra9core to update this file.\n${source
    .replaceAll("{$TLS_EMAIL}", config.deployment.tlsEmail)
    .replaceAll("{$APP_DOMAIN}", config.deployment.appDomain)
    .replaceAll("{$SUPABASE_GATEWAY_ROUTE}", gatewayRoute)
    .replaceAll("{$SUPABASE_STUDIO_SITE}", studioSite)
    .replaceAll("{$APP_PORT}", String(config.deployment.appPort))
    .replaceAll("{$APP_STATIC_ROOT}", config.deployment.appStaticRoot)}`;
}

function renderPrompt(config) {
  const apps = config.project.apps.length ? config.project.apps.map((app) => `- \`${app}\``).join("\n") : "- No application recipe was selected.";
  const gatewayContract = config.deployment.gatewayExposureMode === "private-bff"
    ? "- Gateway exposure: `private-bff`; native Caddy exposes only the application. Kong and Studio remain Docker-private at `http://kong:8000`."
    : `- Gateway exposure: \`public-supabase\`; native Caddy exposes reviewed Supabase gateway routes and protected Studio at \`${config.deployment.studioDomain}\`.`;
  return `# First-run coding-agent brief\n\nThis repository was generated by Infra9CORE. Treat \`.infra9core/config.json\` as the non-secret deployment identity and \`infra/env/.env\` as local secret material. Never commit \`.env\` files, credentials, JWTs, password hashes, provider tokens, or private registry credentials.\n\n## Selected application boundaries\n\n${apps}\n\n## Deployment contract\n\n- Environment: \`${config.deployment.environment}\`\n- Application domain: \`${config.deployment.appDomain}\`\n${gatewayContract}\n- Docker Compose runs private infrastructure; production images must be mirrored to the configured private registry and pinned by digest.\n\n## Required first-run work\n\n1. Read \`docs/adr/0001-product-agnostic-infrastructure-baseline.md\`, \`docs/openapi.yaml\`, and all runbooks before changing infrastructure.\n2. Model the domain and record decisions in new ADRs before application implementation.\n3. Define API contracts before adapters; keep domain logic independent of Supabase and provider SDKs.\n4. Add idempotent forward migrations and matching rollback files. Every application table requires RLS and reviewed policies.\n5. Configure \`infra/env/.env\` locally with real secrets, then run \`make doctor\`.\n6. Add application image build definitions and deliberate Caddy routes only after their ports and health checks are specified.\n7. Add structured request tracing, tests, and operational runbook updates before deployment.\n\n## Guardrails\n\nDo not replace the generated Supabase runtime, weaken loopback bindings, expose Kong or Studio in \`private-bff\` mode, use public production images, or overwrite managed infrastructure files by hand. Use \`make infra9core\` to update managed configuration and review the plan before accepting it.\n`;
}

function renderEnv(source, config) {
  const publicSupabase = config.deployment.gatewayExposureMode === "public-supabase";
  const externalUrl = publicSupabase ? config.deployment.supabasePublicUrl : config.deployment.publicAppUrl;
  const values = {
    PROJECT_SLUG: config.project.slug,
    COMPOSE_PROJECT_NAME: config.project.slug,
    DEPLOY_ENV: config.deployment.environment,
    PUBLIC_APP_URL: config.deployment.publicAppUrl,
    GATEWAY_EXPOSURE_MODE: config.deployment.gatewayExposureMode,
    SUPABASE_PUBLIC_URL: externalUrl,
    SUPABASE_INTERNAL_URL: config.deployment.supabaseInternalUrl,
    API_EXTERNAL_URL: externalUrl,
    SITE_URL: config.deployment.publicAppUrl,
    ADDITIONAL_REDIRECT_URLS: config.deployment.additionalRedirectUrls,
    SUPABASE_BIND_ADDRESS: config.deployment.supabaseBindAddress,
    SUPABASE_API_PORT: config.deployment.supabaseApiPort,
    SUPABASE_STUDIO_PORT: config.deployment.supabaseStudioPort,
    IMAGE_REGISTRY: config.deployment.imageRegistry,
  };
  return Object.entries(values).reduce((result, [key, value]) => setEnv(result, key, String(value)), source);
}

async function ask(question, current, rl) {
  if (yes) return current;
  const answer = (await rl.question(`${question} [${current}]: `)).trim();
  return answer || current;
}

async function askGatewayExposureMode(current, rl) {
  const value = await ask("Gateway exposure mode (private-bff or public-supabase)", current, rl);
  if (!gatewayExposureModes.includes(value)) throw new Error("Gateway exposure mode must be private-bff or public-supabase");
  return value;
}

async function main() {
  const config = JSON.parse(await readFile(configPath, "utf8"));
  // Configurations generated before gateway modes default to their original public behavior.
  config.deployment.gatewayExposureMode ??= "public-supabase";
  config.deployment.supabaseInternalUrl ??= "http://kong:8000";
  const rl = yes ? null : createInterface({ input: process.stdin, output: process.stdout });
  try {
    config.deployment.environment = await ask("Deployment environment", config.deployment.environment, rl);
    config.deployment.appDomain = await ask("Application domain", config.deployment.appDomain, rl);
    config.deployment.studioDomain = await ask("Supabase Studio domain", config.deployment.studioDomain, rl);
    config.deployment.tlsEmail = await ask("TLS contact email", config.deployment.tlsEmail, rl);
    config.deployment.publicAppUrl = await ask("Public application URL", config.deployment.publicAppUrl, rl);
    config.deployment.gatewayExposureMode = await askGatewayExposureMode(config.deployment.gatewayExposureMode, rl);
    if (config.deployment.gatewayExposureMode === "public-supabase") {
      config.deployment.supabasePublicUrl = await ask("Public Supabase URL", config.deployment.supabasePublicUrl, rl);
    }
    config.deployment.imageRegistry = await ask("Private production image registry", config.deployment.imageRegistry, rl);
  } finally { rl?.close(); }

  const envPath = path.join(root, "infra/env/.env.example");
  const caddyExamplePath = path.join(root, "infra/caddy/Caddyfile.example");
  const caddyPath = path.join(root, "infra/caddy/Caddyfile");
  const promptPath = path.join(root, "docs/infra9core/FIRST_RUN_AGENT_PROMPT.md");
  const existingCaddy = await readFile(caddyPath, "utf8").catch((error) => error.code === "ENOENT" ? null : Promise.reject(error));
  if (existingCaddy && !existingCaddy.startsWith("# Managed by Infra9CORE") && !force) {
    throw new Error("Refusing to replace unmanaged infra/caddy/Caddyfile. Use --force-managed-files only after reviewing it.");
  }
  const outputs = [
    [configPath, `${JSON.stringify(config, null, 2)}\n`],
    [envPath, renderEnv(await readFile(envPath, "utf8"), config)],
    [caddyPath, renderCaddy(await readFile(caddyExamplePath, "utf8"), config)],
    [promptPath, renderPrompt(config)],
  ];
  const changed = [];
  for (const [target, content] of outputs) {
    const current = await readFile(target, "utf8").catch((error) => error.code === "ENOENT" ? "" : Promise.reject(error));
    if (current !== content) changed.push(path.relative(root, target));
  }
  console.log("Infra9CORE first-run configuration plan:");
  console.log(`- environment: ${config.deployment.environment}`);
  console.log(`- application domain: ${config.deployment.appDomain}`);
  console.log(`- gateway exposure mode: ${config.deployment.gatewayExposureMode}`);
  console.log(`- private image registry: ${config.deployment.imageRegistry}`);
  console.log(changed.length ? `- files to update: ${changed.join(", ")}` : "- no tracked files require changes");
  if (!yes && changed.length) {
    const confirmationReader = createInterface({ input: process.stdin, output: process.stdout });
    const confirmation = (await confirmationReader.question("Apply this plan? [y/N] ")).trim().toLowerCase();
    confirmationReader.close();
    if (confirmation !== "y" && confirmation !== "yes") { console.log("No files changed."); return; }
  }
  await mkdir(path.dirname(promptPath), { recursive: true });
  for (const [target, content] of outputs) await writeFile(target, content);
  console.log("Configuration complete. Set secrets in infra/env/.env, then run make doctor.");
}

main().catch((error) => { console.error(`Infra9CORE configuration failed: ${error.message}`); process.exitCode = 1; });
